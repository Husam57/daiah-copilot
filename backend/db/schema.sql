-- مخطط قاعدة بيانات رفيق الداعية — الصقه كاملاً في Supabase SQL Editor ثم Run.
-- آمن للتشغيل أكثر من مرة (IF NOT EXISTS / CREATE OR REPLACE).

CREATE EXTENSION IF NOT EXISTS vector;

-- ============ الجداول ============

-- المستخدمون (لوحة التحكم)
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT 'editor',
    CONSTRAINT users_role_check CHECK (role IN ('admin', 'editor'))
);

-- الأقسام (شجرية عبر parent_id)
CREATE TABLE IF NOT EXISTS sections (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT REFERENCES sections(id) ON DELETE SET NULL,
    name_ar     TEXT NOT NULL,
    name_en     TEXT,
    slug        TEXT NOT NULL UNIQUE,
    category    TEXT NOT NULL,
    description TEXT,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT sections_category_check
        CHECK (category IN ('methodology', 'shubuhat', 'intro_islam', 'new_muslim'))
);

-- المواد (المصدر الوحيد للردود الشرعية)
CREATE TABLE IF NOT EXISTS posts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id   BIGINT NOT NULL REFERENCES sections(id) ON DELETE RESTRICT,
    slug         TEXT NOT NULL UNIQUE,
    title_ar     TEXT NOT NULL,
    title_en     TEXT,
    content_ar   TEXT NOT NULL,
    content_en   TEXT,
    summary_ar   TEXT,
    tags         TEXT[] NOT NULL DEFAULT '{}',
    external_ref TEXT,
    topic        TEXT,
    source_name  TEXT,
    content_type TEXT NOT NULL DEFAULT 'article',
    file_url     TEXT,
    status       TEXT NOT NULL DEFAULT 'draft',
    created_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewed_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    published_at TIMESTAMPTZ,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT posts_status_check CHECK (status IN ('draft', 'review', 'published')),
    CONSTRAINT posts_content_type_check
        CHECK (content_type IN ('article', 'booklet', 'leaflet', 'shubha_response'))
);

-- ترقية لقاعدة موجودة مسبقاً (لا يفعل شيئاً إذا كانت الأعمدة والقيد موجودة)
ALTER TABLE posts ADD COLUMN IF NOT EXISTS topic        TEXT;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS source_name  TEXT;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS content_type TEXT NOT NULL DEFAULT 'article';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS file_url     TEXT;
ALTER TABLE posts DROP CONSTRAINT IF EXISTS posts_content_type_check;
ALTER TABLE posts ADD CONSTRAINT posts_content_type_check
    CHECK (content_type IN ('article', 'booklet', 'leaflet', 'shubha_response'));

-- مقاطع المواد المفهرسة (embedding من Gemini بـ 768 بُعداً)
CREATE TABLE IF NOT EXISTS post_chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    lang        TEXT NOT NULL,
    chunk_index INTEGER NOT NULL,
    chunk_text  TEXT NOT NULL,
    embedding   vector(768),
    CONSTRAINT post_chunks_lang_check CHECK (lang IN ('ar', 'en')),
    CONSTRAINT post_chunks_post_lang_idx_key UNIQUE (post_id, lang, chunk_index)
);

-- إعدادات الذكاء الاصطناعي (صف واحد فعّال فقط)
CREATE TABLE IF NOT EXISTS ai_settings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guidance_prompt      TEXT NOT NULL DEFAULT '',
    similarity_threshold DOUBLE PRECISION NOT NULL DEFAULT 0.75,
    top_k                INTEGER NOT NULL DEFAULT 5,
    fallback_message_ar  TEXT NOT NULL,
    fallback_message_en  TEXT NOT NULL,
    version              INTEGER NOT NULL DEFAULT 1,
    is_active            BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by           BIGINT REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT ai_settings_threshold_check
        CHECK (similarity_threshold >= 0 AND similarity_threshold <= 1),
    CONSTRAINT ai_settings_top_k_check CHECK (top_k > 0)
);

-- مراكز الإحالة (تظهر في حالة fallback)
CREATE TABLE IF NOT EXISTS referral_centers (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    TEXT NOT NULL,
    country TEXT,
    url     TEXT,
    contact TEXT
);

-- سجل المحادثات
CREATE TABLE IF NOT EXISTS chat_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        TEXT NOT NULL,
    question          TEXT NOT NULL,
    detected_category TEXT,
    lang              TEXT,
    matched_post_id   BIGINT REFERENCES posts(id) ON DELETE SET NULL,
    score             DOUBLE PRECISION,
    is_fallback       BOOLEAN NOT NULL DEFAULT FALSE,
    feedback          SMALLINT,  -- 1 = مفيد، -1 = غير مفيد، NULL = لم يُقيَّم
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chat_logs_category_check CHECK (
        detected_category IS NULL
        OR detected_category IN ('methodology', 'shubuhat', 'intro_islam', 'new_muslim')
    ),
    CONSTRAINT chat_logs_lang_check CHECK (lang IS NULL OR lang IN ('ar', 'en')),
    CONSTRAINT chat_logs_feedback_check CHECK (feedback IS NULL OR feedback IN (-1, 1))
);

-- ============ الفهارس ============
CREATE INDEX IF NOT EXISTS ix_posts_section_id ON posts (section_id);
CREATE INDEX IF NOT EXISTS ix_posts_status ON posts (status);
CREATE INDEX IF NOT EXISTS ix_post_chunks_post_id ON post_chunks (post_id);
CREATE INDEX IF NOT EXISTS ix_chat_logs_created_at ON chat_logs (created_at);
CREATE INDEX IF NOT EXISTS ix_post_chunks_embedding_hnsw
    ON post_chunks USING hnsw (embedding vector_cosine_ops);

-- البريد فريد بغض النظر عن حالة الأحرف
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (lower(email));

-- ضمان وجود صف إعدادات فعّال واحد فقط
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_settings_single_active
    ON ai_settings (is_active) WHERE is_active;

-- ============ تحديث updated_at تلقائياً ============
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_posts_updated_at ON posts;
CREATE TRIGGER trg_posts_updated_at
    BEFORE UPDATE ON posts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============ Row Level Security ============
-- مفعّل بدون أي سياسات: مفتاح anon/authenticated لا يقرأ ولا يكتب شيئاً.
-- الـ Backend يستخدم مفتاح service role الذي يتجاوز RLS.
ALTER TABLE users            ENABLE ROW LEVEL SECURITY;
ALTER TABLE sections         ENABLE ROW LEVEL SECURITY;
ALTER TABLE posts            ENABLE ROW LEVEL SECURITY;
ALTER TABLE post_chunks      ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_settings      ENABLE ROW LEVEL SECURITY;
ALTER TABLE referral_centers ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_logs        ENABLE ROW LEVEL SECURITY;

-- ============ الصلاحيات ============
-- service_role (الـ Backend) فقط يصل للجداول. anon و authenticated بلا أي صلاحية.
GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;

-- ============ البحث المتجهي ============
-- يرجع أقرب المقاطع للمنشورات المنشورة فقط. similarity = 1 - cosine distance.
-- (match_post_chunks.lang لتمييز المُعامل عن عمود lang)
CREATE OR REPLACE FUNCTION match_post_chunks(
    query_embedding vector(768),
    match_count     int,
    lang            text
)
RETURNS TABLE (post_id bigint, chunk_text text, similarity double precision)
LANGUAGE sql
STABLE
SET search_path = public, extensions
AS $$
    SELECT c.post_id,
           c.chunk_text,
           1 - (c.embedding <=> query_embedding) AS similarity
    FROM post_chunks c
    JOIN posts p ON p.id = c.post_id
    WHERE p.status = 'published'
      AND c.lang = match_post_chunks.lang
      AND c.embedding IS NOT NULL
    ORDER BY c.embedding <=> query_embedding
    LIMIT match_count;
$$;

-- الدالة للـ Backend فقط
REVOKE EXECUTE ON FUNCTION match_post_chunks(vector, int, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION match_post_chunks(vector, int, text) TO service_role;

