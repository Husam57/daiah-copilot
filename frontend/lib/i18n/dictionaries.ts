/** «دقيقة / دقيقتان / 3 دقائق / 11 دقيقة» */
function arMinutes(n: string): string {
  const v = Number(n.replace(/[^0-9]/g, ""));
  if (v === 1) return "دقيقة واحدة";
  if (v === 2) return "دقيقتان";
  if (v >= 3 && v <= 10) return `${n} دقائق`;
  return `${n} دقيقة`;
}

