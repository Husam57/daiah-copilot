export const DICTIONARIES: Record<Locale, Dict> = { ar, en };

export function isLocale(v: unknown): v is Locale {
  return v === "ar" || v === "en";
}

/** أرقام لاتينية في الواجهتين (كما في التصميم المعتمد للأعداد) مع فواصل اللغة. */
export function fmtNumber(n: number | null | undefined, locale: Locale): string {
  if (n === null || n === undefined) return "—";
  return new Intl.NumberFormat(locale === "ar" ? "ar" : "en", { numberingSystem: "latn" }).format(n);
}

export function fmtDate(iso: string | null | undefined, locale: Locale): string {
  if (!iso) return "—";
  return new Intl.DateTimeFormat(locale === "ar" ? "ar" : "en", {
    year: "numeric",
    month: "long",
    day: "numeric",
    numberingSystem: "latn",
  }).format(new Date(iso));
}
